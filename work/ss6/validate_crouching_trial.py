#!/usr/bin/env python3
"""Crouching slash input-boundary, whole actor entry/playback and live contacts."""
import hashlib,itertools,json,random,struct
from validate_contact_trial import run,validate_pixels,ROOT,ASSETS,PROBE,VIEWER
from validate_match_flow import play
from round_entry_oracle import fixture
from mips_probe import signed

def main():
 cases=[];instructions=visits=states=requests=0
 for attack,player,distance,defense in itertools.product([5,6],[0,1],[64,77.75,78,78.25,100,180],[0,3,4,7]):
  commands=[f'place 280 {280+distance}',f'command {player} 7',f'command {1-player} {defense}','tick 1',f'command {player} {attack}']
  rows=run(commands+['tick 1']*240);base=2+player*11;target=2+(1-player)*11;extra=108+player*16
  action=(195 if attack==6 else 191)+int(distance>=78);state=9 if attack==6 else 1
  assert rows[len(commands)][base+1:base+5]==[1,state,action,0]
  assert rows[-1][base+1:base+4]==[0,1,4]
  hit=distance<180 and defense in [0,7]
  damage=(34 if distance<78 else 38) if attack==6 else (8 if distance<78 else 9)
  assert rows[-1][target]==200-(damage if hit else 0),(attack,player,distance,defense,rows[-1][target])
  assert rows[-1][base+9:base+11]==([1,0] if hit else [0,1] if distance<180 else [0,0])
  #Use unmodified14c2d0 from the existing171-feature boundary. Input is the
  #documented raw edge plus down predicate, not a guessed action identifier.
  p,a,o,b=fixture(player);other=0x1c00000+(1-player)*0xf2c;other_obj=0x1e01000
  p.write(other,other_obj,4);p.write(b+0x24c+(1-player)*4,other,4)
  def original(fn,args=()):
   nonlocal instructions,visits,requests
   result,n=p.run(fn,[signed(v&0xffffffff,32) for v in args],limit=2000000);instructions+=n
   visits+=fn==0x149d08;requests+=fn==0x14c2d0;return result
  def float_word(v):return struct.unpack('<I',struct.pack('<f',v))[0]
  original(0x149008,[a,0]);original(0x149918,[a]);original(0x11d8e0,[o])
  p.write(o+0x40,float_word(rows[len(commands)-1][base+5]),4)
  p.write(other_obj+0x40,float_word(rows[len(commands)-1][target+5]),4)
  original(0x14ff80,[a+0x18c,0,1]);original(0x149d08,[a]);original(0x149918,[a]);original(0x11d8e0,[o])
  p.write(a+0x244,0x4000 if distance>=78 else 0,4)
  p.write(a+0x2c4+(8 if attack==6 else 6)*4,1,4);p.write(a+0x2c4+0xfc,1,4)
  assert original(0x14c2d0,[a]) and p.read(a+0x192,2)==state
  original(0x149d08,[a]);original(0x149918,[a]);original(0x11d8e0,[o])
  for tick,r in enumerate(rows[len(commands):len(commands)+125]):
   if tick:
    prev=rows[len(commands)+tick-1]
    p.write(o+0x30,int(prev[base+8]),4);p.write(a+0x1ac,int(r[base+8]),4)
    #A fresh contact installs timer0 BEFORE this animation pass; its first
    #freeze cannot be inferred from the previous post-frame timer alone.
    freeze=prev[base+6]>0 or r[base+6]>prev[base+6]
    p.write(o+0x104,(p.read(o+0x104,4)&~0x30)|(0x30 if freeze else 0),4);p.write(o+0xfe,6 if freeze else 0,2)
    original(0x11d730,[o]);original(0x11d6c8,[o]);original(0x149d08,[a]);original(0x149918,[a]);original(0x11d8e0,[o])
   expected=[p.read(a+0x194,2),p.read(a+0x196,2),p.read(a+0x19a,1),p.read(a+0x160,4),
    p.read(a+0x23c,4)&0x1e0f,*[p.read(o+off,4) for off in [0x24,0x28,0x2c,0xc0]]]
   #Only the entry pose/armed fields are projected; contact-produced
   #guard/freeze bits are not generated by an isolated actor dispatcher.
   actual=[r[base+1],r[base+2],r[extra+6],r[extra+5],int(r[extra+4])&0x1e0f,r[base+3],r[base+4],r[49+player*6],r[48+player*6]]
   assert actual==expected,(attack,player,distance,defense,tick,[(i,x,y) for i,(x,y) in enumerate(zip(actual,expected)) if x!=y])
   states+=1
  cases.append(dict(attack=attack,player=player,distance=distance,defense=defense,action=action,life=rows[-1][target]))
  if distance in [64,100] and defense in [0,4,7]:
   name=f'crouch-{attack}-{player}-{distance}-{defense}'
   (ROOT/'work/ss6/scenarios'/f'{name}.txt').write_text('\n'.join(commands)+'\n')
 print('crouching entry/playback/contact cases',len(cases),flush=True)
 #Releasing down during a swing must not stand up or shorten the attack.
 for attack in [5,6]:
  r=run(['place 240 500','command 0 7',f'command 0 {attack}','tick 5','command 0 0']+['tick 1']*150)
  assert r[5][3]==1 and r[-1][3:6]==[0,0,0]
  assert any(row[3:6]==[0,1,4] for row in r)
  assert min(row[24] for row in r)==(84 if attack==6 else 96)*256
 #An actual enemy strike arrives during the one-visit normal1 entry gap.
 #A stale queued idle used to be able to replace that new crouching hurt.
 interrupt=['place 280 460','command 0 7','command 0 6','tick 47','command 1 6']
 interrupted=run(interrupt+['tick 1']*160)
 before=next(r for r in interrupted if r[0]==65);hit=next(r for r in interrupted if r[0]==66)
 assert before[3:5]==[0,1] and before[114]==12
 assert hit[3:7]==[2,40,354,0] and hit[2]<before[2]
 assert any(r[5]==354 and r[6]>0 for r in interrupted)
 assert interrupted[-1][3:6]==[0,1,4]
 (ROOT/'work/ss6/scenarios/crouch-recovery-interrupt.txt').write_text('\n'.join(interrupt)+'\n')
 #Crouching heavy trades use the original lower-body counter hurt372.
 trade=['place 280 344','command 0 7','command 1 7','command 0 6','command 1 6']
 rows=run(trade+['tick 1']*250)
 assert any(r[5]==r[16]==372 for r in rows) and rows[-1][2]==rows[-1][13]==166
 double=run(['rounds','life 0 1','life 1 1',*trade]+['tick 1']*800)
 assert any(r[1]==2 for r in double) and double[-1][105]==1 and double[-1][2]==double[-1][13]==200
 rng=random.Random(191195);commands=[]
 for _ in range(64):
  commands+=['reset',f'place 280 {320+rng.randrange(150)}']
  for __ in range(100):commands += [f'command {rng.randrange(2)} {rng.randrange(8)}',f'tick {rng.randrange(1,15)}']
 random_rows=run(commands);assert all(0<=r[2]<=200 and 0<=r[13]<=200 for r in random_rows)
 matches=[]
 for order in [[0,0],[1,1],[0,1,0]]:
  commands,case=play(order,attack=6,interval=90,crouching=True);matches.append(case)
  (ROOT/'work/ss6/scenarios'/('crouch-match-'+''.join(map(str,order))+'.txt')).write_text('\n'.join(commands)+'\n')
  print('crouching heavy match',order,case['updates'],flush=True)
 pixels={str(attack):validate_pixels(heavy=attack==6,crouching=True) for attack in [5,6]}
 report=dict(status='passed_for_integration_fixture',scenarios=cases,whole14c2d0_requests=requests,whole149d08_visits=visits,
  projected_states=states,original_instructions=instructions,random_snapshots=len(random_rows),matches=matches,pixels=pixels,
  probe_sha256=hashlib.sha256(PROBE.read_bytes()).hexdigest(),viewer_sha256=hashlib.sha256(VIEWER.read_bytes()).hexdigest(),
  scope='Armed resource00/system0 crouching light/heavy191/192/195/196 via raw slash edges plus down. Whole14c2d0 raw-feature boundary and149d08 entry/playback projections import native first anchor and freeze/delta schedule;compare state,metadata,conditions,posture,ACT clock,terminal4 jump and deferred normal1 entry. Actual hit/standguard/crouchguard/crouched target,78 boundary,whiff,down release,heavy trade372,doubleKO,next round,mixed controls and natural2-0/0-2/2-1. Independent PIL pixels,not original full frames/GS. Full pad dispatch,cancels,jump/medium slashes,other characters/systems and audio remain outside live scope.')
 (ROOT/'outputs/ss6-feasibility/crouching_trial_validation.json').write_text(json.dumps(report,indent=2)+'\n')
 print(json.dumps({k:(len(v) if k=='scenarios' else v) for k,v in report.items() if k!='matches'},indent=2))
if __name__=='__main__':main()
